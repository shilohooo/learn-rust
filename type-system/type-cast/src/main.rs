#![allow(overflowing_literals)]

/// 类型系统 - 类型转换
///
/// Rust 没有提供原生类型的隐式转换（coercion），但可以使用 as 关键字来进行显式转换（casting）
///
/// 整型之间的转换大体遵循 C 语言的惯例
///
/// 总结：
/// - 大类型转小类型，例如：`u32 as u8`，只保留最低位，高位直接丢弃，相当于对目标类型的最大值加上 1 进行取模
/// - 小类型转大类型，例如：`u8 as u32`
///   - 无符号 = 高位补 0
///   - 有符号 = 符号位扩展：原来的值是负数，那高位补1，原来的值是整数，高位补 0
/// - 有符号和无符号类型相互转换（位模式不变）
///   - `-1i8` 转 `u8` = `1111 1111` -> `1111 1111` = `-1` 转为 `255`
///   - `232u8` 转 `i8` = `1110 1000` -> 最高位是 1，说明是负数，由原码数值位取反再加 1 -> `1001 0111` 加 1
/// - 浮点数与整数之间的转换
///   - 浮点数 转 整数：向零取整（Truncation）。也就是直接删掉小数点后的部分（6.9 as i32 变成 6，-6.9 as i32 变成 -6）。
///   注意：如果浮点数值超过了整数能表示的范围，旧版本 Rust 会导致未定义行为，但现代 Rust（1.45.0+） 会将其“饱和”到整数的最大或最小值（例如 300.0_f32 as u8 会得到 255）。
///   - 整数 转 浮点数：通常比较安全。但如果整数很大（比如 i64 转 f32），可能会发生精度损失，结果会取最接近的浮点数值。
/// - 布尔值与字符转换
///   - bool 转 整数： false 变 0，true 变 1。
///   - 整数 转 bool： 禁止直接使用 as。必须写显式逻辑：x != 0。
///   - u8 转 char： 允许，因为 u8 对应 ASCII 范围。
///   - 其他整数 转 char： 禁止直接使用 as（因为 char 是 4 字节 Unicode，且必须是有效的码点）。需要使用 std::char::from_u32。
fn main() {
    let decimal = 65.4321_f32;
    // 下面这个类型转换语句会报错，因为 Rust 没有提供原生类型之间的隐式转换
    // let integer: u8 = decimal;

    // 显式转换
    let integer = decimal as u8;
    let character = integer as char;

    println!("Casting: {} -> {} -> {}", decimal, integer, character);

    // 当把任何类型转换为无符号类型 T 时，它的值会一直加上/减去（std::T::Max + 1）
    // 直到值位于新类型 T 的有效范围内

    // u16 的有效数值范围已经包含了 1000
    println!("1000 as a u16 is: {}", 1000 as u16);
    // u8 类型最大值：255
    println!("u8 max value is: {}", u8::MAX);
    // -1 转换 u8，由于 u8 式无符号类型，因此转换时将会把 -1 加上 (u8 最大值 + 1)
    // 也就是 -1 + (255 + 1) = -1 + 256 = 255
    println!("-1 as a u8 is: {}", (-1i8) as u8);

    // 正数大整型转换为小整形
    // 1000 - 256 - 256 - 256 = 232
    // 事实上的处理方式是：从最低有效位（LSB，least significant bits）开始保留
    // 8 位，然后剩余位置，直到最高有效位（MSB，most significant bit）都被抛弃。
    // 译注：MSB 就是二进制的最高位，LSB 就是二进制的最低位，按日常书写习惯就是
    // 最左边一位和最右边一位。
    println!("1000 as a u8 is : {}", 1000i16 as u8);
    // 对正数，这就和取模一样。1000 % (u8::Max + 1)
    println!("1000 mod 256 = {}", 1000 % 256);

    // 当转换到有符号类型时，（位操作的）结果就和 “先转换到对应的无符号类型，
    // 如果 MSB 是 1，则该值为负” 是一样的。
    // 当然如果数值已经在目标类型的范围内，就直接把它放进去。
    println!("128 as a i16 is: {}", 128 as i16);
    // 128 转成 u8 还是 128，但转到 i8 相当于给 128 取八位的二进制补码，其值是：
    println!("128 as a i8 is : {}", 128i16 as i8);

    // 重复之前的例子
    // 1000 as u8 = 1000 % 256 = 232
    println!("1000 as a i8 is : {}", 1000i16 as u8);
    // 232 的二进制补码是 -24
    println!(" 232 as a i8 is : {}", 232i16 as i8);
}
