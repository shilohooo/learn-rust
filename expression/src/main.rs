/// 表达式
fn main() {
    // 变量绑定语句
    let x = 5;
    // 表达式带分号
    x;
    x + 1;
    15;

    // 代码块也是表达式，所以它们可以用作赋值中的值。
    // 代码块中的最后一个表达式将赋给适当的表达式，例如局部变量。
    // 但是，如果代码块的最后一个表达式结尾处有分号，则返回值为 ()
    // 注意：代码块中的最后一个语句是代码块中实际执行的最后一个语句，而不一定是代码块中最后一行的语句。
    let z = { 2 };

    let y = 5u32;

    let b = {
        let squared = x * x;
        let cube = squared * x;
        // 将下面这个表达式的值赋值给变量 b
        cube + squared + x
    };

    println!("x = {}", x);
    println!("y = {}", y);
    println!("b = {}", b);
}
