/// `F` 必须是泛型
/// 当闭包被定义，编译器会隐式地创建一个匿名类型的结构体，用以储存闭包捕获的变量，
///
/// 同时为这个未知类型的结构体实现函数功能，
///
/// 通过 `Fn`、`FnMut` 或 `FnOnce` 三种 `trait` 中的一种。
///
/// 若使用闭包作为函数参数，由于这个结构体的类型未知，任何的用法都要求是泛型的。
///
/// 然而，使用未限定类型的参数 <T> 过于不明确，并且是不允许的。
///
/// 事实上，指明为该结构体实现的是 `Fn`、`FnMut`、或 `FnOnce` 中的哪种 `trait`，
///
/// 对于约束该结构体的类型而言就已经足够了。
///
/// `where F: FnOnce()` 限制了泛型 F 必须是一个没有入参和返回值的闭包实现 `Fn`
fn apply<F>(f:F)
where F: FnOnce() {
    f();
}

/// # 闭包中的类型匿名
fn main() {
    let x = 7;

    // 注意这个闭包的类型是：fn()
    // 它没有入参，也没有返回值，或者说返回值是 `()`
    // 符合 apply 函数的参数类型要求～
    let my_print = || println!("{}", x);

    apply(my_print);
}
